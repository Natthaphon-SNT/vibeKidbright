/* framebuffer 128×64 = 1024 bytes */
static uint8_t s_oled_fb[1024];

// ── Low-level I²C helpers ─────────────────────────────────────────────────

static void oled_cmd(uint8_t cmd)
{
    uint8_t buf[2] = {0x00, cmd};
    i2c_master_transmit(s_oled_dev, buf, 2, 10);
}

static void oled_init(void)
{
    /* Init I²C – new master bus API */
    i2c_master_bus_config_t bus_cfg = {
        .i2c_port          = I2C_NUM_0,
        .sda_io_num        = OLED_SDA_PIN,
        .scl_io_num        = OLED_SCL_PIN,
        .clk_source        = I2C_CLK_SRC_DEFAULT,
        .glitch_ignore_cnt = 7,
        .flags.enable_internal_pullup = true,
    };
    ESP_ERROR_CHECK(i2c_new_master_bus(&bus_cfg, &s_i2c_bus));

    i2c_device_config_t dev_cfg = {
        .dev_addr_length = I2C_ADDR_BIT_LEN_7,
        .device_address  = OLED_ADDR,
        .scl_speed_hz    = OLED_I2C_FREQ,
    };
    ESP_ERROR_CHECK(i2c_master_bus_add_device(s_i2c_bus, &dev_cfg, &s_oled_dev));

    /* SH1106 init sequence */
    oled_cmd(0xAE); // display off
    oled_cmd(0xD5); oled_cmd(0x80); // clock div
    oled_cmd(0xA8); oled_cmd(0x3F); // mux ratio 64
    oled_cmd(0xD3); oled_cmd(0x00); // display offset
    oled_cmd(0x40);                  // start line 0
    oled_cmd(0x8D); oled_cmd(0x14); // charge pump on
    oled_cmd(0x20); oled_cmd(0x00); // horizontal addressing
    oled_cmd(0xA1);                  // seg remap
    oled_cmd(0xC8);                  // com scan direction
    oled_cmd(0xDA); oled_cmd(0x12); // com pins
    oled_cmd(0x81); oled_cmd(0xCF); // contrast
    oled_cmd(0xD9); oled_cmd(0xF1); // pre-charge
    oled_cmd(0xDB); oled_cmd(0x40); // vcomh
    oled_cmd(0xA4);                  // all pixels off (RAM)
    oled_cmd(0xA6);                  // normal display
    oled_cmd(0xAF);                  // display on

    memset(s_oled_fb, 0, sizeof(s_oled_fb));
}

/* flush framebuffer → OLED (SH1106 อาจต้องชดเชย column +2) */
static void oled_flush(void)
{
    for (int page = 0; page < 8; page++) {
        oled_cmd(0xB0 | page);
        oled_cmd(0x02);  // column low  (SH1106 offset = 2)
        oled_cmd(0x10);  // column high

        uint8_t buf[129];
        buf[0] = 0x40; // Co=0, D/C=1
        memcpy(&buf[1], &s_oled_fb[page * 128], 128);
        i2c_master_transmit(s_oled_dev, buf, 129, 10);
    }
}

/* วาดตัวอักษร 8×8 ที่ตำแหน่ง (col, page) */
static void oled_draw_char(int col, int page, char c)
{
    if (c < 0x20 || c > 0x7E) c = ' ';
    const uint8_t *glyph = font8x8[(uint8_t)(c - 0x20)];
    int idx = page * 128 + col;
    for (int i = 0; i < 8 && col + i < 128; i++) {
        s_oled_fb[idx + i] = glyph[i];
    }
}

/* วาดสตริงที่ (col, page) */
static void oled_draw_str(int col, int page, const char *str)
{
    while (*str && col < 128) {
        oled_draw_char(col, page, *str++);
        col += 8;
    }
}

/* ล้างหน้า (page = 0..7) */
static void oled_clear_page(int page)
{
    memset(&s_oled_fb[page * 128], 0, 128);
}

/* แสดงข้อความบรรทัดเดียว (ล้าง 2 page แล้วเขียนใหม่) */
static void oled_show_line(int page, const char *text)
{
    oled_clear_page(page);
    oled_draw_str(0, page, text);
}

// ─────────────────────────────────────────────────────────────────────────────
// Joystick / ESP-NOW
// ─────────────────────────────────────────────────────────────────────────────
static uint8_t car_mac[] = {0xF8, 0xB3, 0xB7, 0x2A, 0xF9, 0x28};

#define JS_X_CH     ADC1_CHANNEL_6   // GPIO34
#define JS_Y_CH     ADC1_CHANNEL_7   // GPIO35
#define SW1         16
#define SW2         14

#define X_MIN       0
#define X_CENTER    1680
#define X_MAX       4095
#define Y_MIN       0
#define Y_CENTER    1794
#define Y_MAX       4095
#define DEAD_ZONE   10

static volatile bool s_espnow_ready = false; // set จาก send callback

static int32_t map_val(int32_t x, int32_t in_min, int32_t in_max,
                       int32_t out_min, int32_t out_max)
{
    return (x - in_min) * (out_max - out_min) / (in_max - in_min) + out_min;
}

static int32_t constrain_val(int32_t x, int32_t lo, int32_t hi)
{
    if (x < lo) return lo;
    if (x > hi) return hi;
    return x;
}

static int32_t abs_val(int32_t x) { return x < 0 ? -x : x; }

// ── ESP-NOW send callback ─────────────────────────────────────────────────

// ESP-IDF v5.5.4: callback receives wifi_tx_info_t* instead of MAC address
static void on_sent(const wifi_tx_info_t *tx_info, esp_now_send_status_t status)
{
    (void)tx_info;
    s_espnow_ready = (status == ESP_NOW_SEND_SUCCESS);
}

// ── Init functions ────────────────────────────────────────────────────────

static void adc_init(void)
{
    // New ADC oneshot API (replaces deprecated adc1_config_* functions)
    adc_oneshot_unit_init_cfg_t unit_cfg = {
        .unit_id  = ADC_UNIT_1,
        .ulp_mode = ADC_ULP_MODE_DISABLE,
    };
    ESP_ERROR_CHECK(adc_oneshot_new_unit(&unit_cfg, &s_adc1));

    adc_oneshot_chan_cfg_t ch_cfg = {
        .atten    = ADC_ATTEN_DB_12,  // replaces deprecated ADC_ATTEN_DB_11
        .bitwidth = ADC_BITWIDTH_12,
    };
    ESP_ERROR_CHECK(adc_oneshot_config_channel(s_adc1, ADC_CHANNEL_6, &ch_cfg)); // GPIO34
    ESP_ERROR_CHECK(adc_oneshot_config_channel(s_adc1, ADC_CHANNEL_7, &ch_cfg)); // GPIO35
}

static void gpio_init_pins(void)
{
    gpio_config_t io = {
        .pin_bit_mask = (1ULL << SW1) | (1ULL << SW2),
        .mode         = GPIO_MODE_INPUT,
        .pull_up_en   = GPIO_PULLUP_ENABLE,
        .pull_down_en = GPIO_PULLDOWN_DISABLE,
        .intr_type    = GPIO_INTR_DISABLE,
    };
    gpio_config(&io);
}

static void espnow_init(void)
{
    ESP_ERROR_CHECK(nvs_flash_init());
    ESP_ERROR_CHECK(esp_netif_init());
    ESP_ERROR_CHECK(esp_event_loop_create_default());

    wifi_init_config_t cfg = WIFI_INIT_CONFIG_DEFAULT();
    ESP_ERROR_CHECK(esp_wifi_init(&cfg));
    ESP_ERROR_CHECK(esp_wifi_set_mode(WIFI_MODE_STA));
    ESP_ERROR_CHECK(esp_wifi_start());
    ESP_ERROR_CHECK(esp_wifi_disconnect());

    uint8_t mac[6];
    esp_wifi_get_mac(WIFI_IF_STA, mac);
    ESP_LOGI(TAG, "My MAC: %02X:%02X:%02X:%02X:%02X:%02X",
             mac[0], mac[1], mac[2], mac[3], mac[4], mac[5]);

    ESP_ERROR_CHECK(esp_now_init());
    ESP_ERROR_CHECK(esp_now_register_send_cb(on_sent));

    esp_now_peer_info_t peer = {};
    memcpy(peer.peer_addr, car_mac, 6);
    peer.channel = 1;
    peer.encrypt = false;
    ESP_ERROR_CHECK(esp_now_add_peer(&peer));

    ESP_LOGI(TAG, "Controller ready");
}

// ── Main task ─────────────────────────────────────────────────────────────

static void controller_task(void *arg)
{
    /* แสดง "ESP-NOW READY" ครั้งแรก */
    oled_show_line(0, "ESP-NOW READY");
    oled_show_line(2, "DIR: STOP");
    oled_flush();

    char prev_dir[16] = "";
    bool  prev_ready  = true;

    for (;;) {
        int rx = 0, ry = 0;
        adc_oneshot_read(s_adc1, ADC_CHANNEL_6, &rx);
        adc_oneshot_read(s_adc1, ADC_CHANNEL_7, &ry);

        int joy_x = (rx >= X_CENTER)
            ? (int)map_val(rx, X_CENTER, X_MAX,    0,    100)
            : (int)map_val(rx, X_MIN,    X_CENTER, -100, 0);

        int joy_y = (ry >= Y_CENTER)
            ? (int)map_val(ry, Y_CENTER, Y_MAX,    0,    100)
            : (int)map_val(ry, Y_MIN,    Y_CENTER, -100, 0);

        joy_x = (int)constrain_val(-joy_x, -100, 100);
        joy_y = (int)constrain_val(-joy_y, -100, 100);

        int32_t cmd = 999;

        if (abs_val(joy_y) >= abs_val(joy_x)) {
            if (joy_y > DEAD_ZONE) {
                cmd = constrain_val(joy_y, 1, 100);
            } else if (joy_y < -DEAD_ZONE) {
                cmd = constrain_val(joy_y, -100, -1);
            }
        } else {
            if (joy_x > DEAD_ZONE) {
                cmd = constrain_val(joy_x, 1, 100) + 400;
            } else if (joy_x < -DEAD_ZONE) {
                cmd = constrain_val(joy_x, -100, -1) + 400;
            }
        }

        esp_now_send(car_mac, (uint8_t *)&cmd, sizeof(cmd));

        /* ─── ทิศทาง ─── */
        const char *dir = "STOP";
        if      (cmd >= 1    && cmd <= 100) dir = "FORWARD";
        else if (cmd >= -100 && cmd <= -1)  dir = "BACKWARD";
        else if (cmd >= 401  && cmd <= 500) dir = "RIGHT";
        else if (cmd >= 300  && cmd <= 399) dir = "LEFT";

        ESP_LOGI(TAG, "X:%d Y:%d CMD:%ld | %s", joy_x, joy_y, (long)cmd, dir);

        /* ─── อัปเดต OLED เฉพาะเมื่อค่าเปลี่ยน ─── */
        bool cur_ready = s_espnow_ready;
        bool changed   = false;

        if (cur_ready != prev_ready) {
            oled_show_line(0, cur_ready ? "ESP-NOW READY" : "ESP-NOW FAIL");
            prev_ready = cur_ready;
            changed = true;
        }

        if (strcmp(dir, prev_dir) != 0) {
            char line[24];
            snprintf(line, sizeof(line), "DIR: %s    ", dir); // เติม space ล้างตัวเก่า
            oled_show_line(2, line);
            strncpy(prev_dir, dir, sizeof(prev_dir) - 1);
            changed = true;
        }

        if (changed) {
            oled_flush();
        }

        vTaskDelay(pdMS_TO_TICKS(50));
    }
}

// ── Entry point ───────────────────────────────────────────────────────────
void app_main(void)
{
    gpio_init_pins();
    adc_init();
    oled_init();       // ← init OLED ก่อน espnow
    espnow_init();

    xTaskCreate(controller_task, "controller_task", 4096, NULL, 5, NULL);
}