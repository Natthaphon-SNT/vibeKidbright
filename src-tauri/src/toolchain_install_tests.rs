//! ZIP hashes here certify only synthetic test bytes, never production assets.
use super::*;
use sha2::{Digest, Sha256};
use std::{cell::Cell, fs, io::Cursor};

fn zip_bytes(name: &str, bytes: &[u8]) -> Vec<u8> {
    let mut writer = zip::ZipWriter::new(Cursor::new(Vec::new()));
    writer
        .start_file(name, zip::write::SimpleFileOptions::default())
        .unwrap();
    writer.write_all(bytes).unwrap();
    writer.finish().unwrap().into_inner()
}

fn fixture_manifest(frameworks: &[u8], tools: &[u8]) -> serde_json::Value {
    let assets: Vec<_> = crate::toolchain_integrity::PART_IDS.iter().zip([frameworks, tools]).map(|(id, bytes)| {
        serde_json::json!({
            "id": id, "asset_identity": format!("fixture:{id}"),
            "platform": crate::toolchain_integrity::host_platform(), "version": TOOLCHAIN_VERSION,
            "download_url": "https://example.invalid/test-only.zip", "trust": "verified",
            "expected_sha256": format!("{:x}", Sha256::digest(bytes)),
            "provenance": "Synthetic ZIP fixture generated by this test; not publisher evidence.",
            "checked_date": "2026-11-04", "reason": "test only"
        })
    }).collect();
    serde_json::json!({"schema_version": 1, "assets": assets})
}

fn plan(json: &serde_json::Value) -> Result<Vec<Asset>, String> {
    Manifest::parse(&json.to_string())?.plan(
        &crate::toolchain_integrity::host_platform(),
        TOOLCHAIN_VERSION,
        None,
    )
}

pub(super) fn archives_for_activation() -> Vec<VerifiedArchive> {
    let bytes = zip_bytes("test.txt", b"fixture");
    plan(&fixture_manifest(&bytes, &bytes))
        .unwrap()
        .into_iter()
        .map(|asset| {
            VerifiedArchive::acquire(asset, &AtomicBool::new(false), |file| {
                file.write_all(&bytes).map_err(|e| e.to_string())
            })
            .unwrap()
        })
        .collect()
}

fn install(
    destination: &Path,
    json: &serde_json::Value,
    frameworks: &[u8],
    tools: &[u8],
    stages: &mut Vec<String>,
) -> Result<(), String> {
    let parts = plan(json)?;
    install_verified_parts(
        destination,
        &parts,
        &AtomicBool::new(false),
        |asset, file| {
            file.write_all(if asset.id == "kidbright-frameworks" {
                frameworks
            } else {
                tools
            })
            .map_err(|e| e.to_string())
        },
        |stage, _, _| stages.push(stage.to_string()),
    )
}

fn previous(temp: &Path) -> PathBuf {
    let dest = temp.join("toolchain");
    fs::create_dir(&dest).unwrap();
    fs::write(dest.join("old-sdk"), "keep me").unwrap();
    fs::write(dest.join(SENTINEL_FILE), "old-version").unwrap();
    dest
}

fn assert_previous(dest: &Path) {
    assert_eq!(fs::read_to_string(dest.join("old-sdk")).unwrap(), "keep me");
    assert_eq!(
        fs::read_to_string(dest.join(SENTINEL_FILE)).unwrap(),
        "old-version"
    );
    assert_eq!(fs::read_dir(dest).unwrap().count(), 2);
    assert!(!fs::read_dir(dest.parent().unwrap())
        .unwrap()
        .any(|entry| entry
            .unwrap()
            .file_name()
            .to_string_lossy()
            .starts_with(".toolchain-install-")));
}

#[test]
fn matching_fixture_installs_both_parts_and_keeps_unrelated_stale_files() {
    let temp = tempfile::tempdir().unwrap();
    let dest = previous(temp.path());
    let stale = temp.path().join("toolchain.installing");
    fs::create_dir(&stale).unwrap();
    fs::write(stale.join("_download_0.zip"), "old cache, not this run").unwrap();
    let backup = temp.path().join("toolchain.backup");
    fs::create_dir(&backup).unwrap();
    fs::write(backup.join("keep"), "previous evidence").unwrap();
    let frameworks = zip_bytes("esp-idf/version.txt", b"fixture IDF");
    let tools = zip_bytes(".espressif/tool.txt", b"fixture tool");
    let mut stages = Vec::new();
    install(
        &dest,
        &fixture_manifest(&frameworks, &tools),
        &frameworks,
        &tools,
        &mut stages,
    )
    .unwrap();
    assert_eq!(
        fs::read(dest.join("esp-idf/version.txt")).unwrap(),
        b"fixture IDF"
    );
    assert_eq!(
        fs::read(dest.join(".espressif/tool.txt")).unwrap(),
        b"fixture tool"
    );
    assert_eq!(
        fs::read_to_string(dest.join(SENTINEL_FILE)).unwrap(),
        TOOLCHAIN_VERSION
    );
    assert!(!dest.join("old-sdk").exists());
    assert_eq!(
        fs::read(stale.join("_download_0.zip")).unwrap(),
        b"old cache, not this run"
    );
    assert_eq!(fs::read(backup.join("keep")).unwrap(), b"previous evidence");
    assert_eq!(stages.last().unwrap(), "verifying");
    assert!(!fs::read_dir(temp.path()).unwrap().any(|entry| entry
        .unwrap()
        .file_name()
        .to_string_lossy()
        .starts_with(".toolchain-install-")));
}

#[test]
fn mismatch_modified_and_truncated_zip_stop_before_any_extraction() {
    let bytes = zip_bytes("new-sdk", b"test");
    for mode in [
        "wrong expected hash",
        "modified bytes",
        "truncated bytes",
        "second part mismatch",
    ] {
        let temp = tempfile::tempdir().unwrap();
        let dest = previous(temp.path());
        let mut manifest = fixture_manifest(&bytes, &bytes);
        let mut input = bytes.clone();
        let mut second = bytes.clone();
        match mode {
            "wrong expected hash" => {
                manifest["assets"][0]["expected_sha256"] = "00".repeat(32).into()
            }
            "modified bytes" => input[0] ^= 1,
            "truncated bytes" => input.truncate(input.len() / 2),
            _ => second[0] ^= 1,
        }
        let mut stages = Vec::new();
        assert!(
            install(&dest, &manifest, &input, &second, &mut stages)
                .unwrap_err()
                .contains("SHA-256 mismatch"),
            "{mode}"
        );
        assert!(!stages.iter().any(|stage| stage == "extracting"));
        assert_previous(&dest);
    }
}

#[test]
fn missing_unverified_incomplete_or_ambiguous_manifest_never_acquires_an_archive() {
    let bytes = zip_bytes("test", b"test");
    for mode in [
        "missing",
        "unverified",
        "missing hash",
        "invalid hash",
        "missing provenance",
        "ambiguous",
        "schema",
    ] {
        let temp = tempfile::tempdir().unwrap();
        let dest = temp.path().join("not-created/toolchain");
        let mut manifest = fixture_manifest(&bytes, &bytes);
        match mode {
            "missing" => {
                manifest["assets"].as_array_mut().unwrap().remove(0);
            }
            "unverified" => manifest["assets"][0]["trust"] = "unverified".into(),
            "missing hash" => manifest["assets"][0]["expected_sha256"] = serde_json::Value::Null,
            "invalid hash" => manifest["assets"][0]["expected_sha256"] = "not-a-sha256".into(),
            "missing provenance" => manifest["assets"][0]["provenance"] = serde_json::Value::Null,
            "ambiguous" => {
                let duplicate = manifest["assets"][0].clone();
                manifest["assets"].as_array_mut().unwrap().push(duplicate);
            }
            _ => manifest["schema_version"] = 2.into(),
        }
        let mut stages = Vec::new();
        assert!(
            install(&dest, &manifest, &bytes, &bytes, &mut stages).is_err(),
            "{mode}"
        );
        assert!(stages.is_empty());
        assert!(!dest.parent().unwrap().exists());
    }
}

