// ---- Framebuffer ----
static uint8_t s_oled_fb[1024];
 
// ---- SH1106: write command ----
static esp_err_t sh1106_write_cmd(uint8_t cmd) {
    uint8_t buf[2] = {0x00, cmd};
    return i2c_master_write_to_device(I2C_PORT_OLED, OLED_ADDR, buf, 2, pdMS_TO_TICKS(50));
}
 
// ---- SH1106: init sequence ----
static esp_err_t sh1106_init(void) {
    vTaskDelay(pdMS_TO_TICKS(100));
    uint8_t cmds[] = {
        0xAE,       // Display OFF
        0xD5, 0x80, // Clock divide
        0xA8, 0x3F, // Multiplex ratio 64
        0xD3, 0x00, // Display offset 0
        0x40,       // Start line 0
        0xAD, 0x8B, // Internal DC-DC ON (SH1106)
        0xA1,       // Segment remap
        0xC8,       // COM scan direction
        0xDA, 0x12, // COM pins
        0x81, 0xCF, // Contrast
        0xD9, 0xF1, // Pre-charge
        0xDB, 0x40, // VCOMH
        0xA4,       // Resume display
        0xA6,       // Normal display
        0xAF        // Display ON
    };
    for (size_t i = 0; i < sizeof(cmds); i++) {
        if (sh1106_write_cmd(cmds[i]) != ESP_OK) return ESP_FAIL;
    }
    return ESP_OK;
}
 
// ---- SH1106: flush framebuffer ----
// SH1106 มี internal RAM 132 columns ต้องชดเชย offset 2
static esp_err_t sh1106_update(void) {
    uint8_t buf[130];  // 0x40 + 128 bytes
    for (uint8_t page = 0; page < 8; page++) {
        sh1106_write_cmd(0xB0 + page);   // Page address
        sh1106_write_cmd(0x02);           // Lower column = 2 (offset SH1106)
        sh1106_write_cmd(0x10);           // Higher column = 0
        buf[0] = 0x40;                    // Data mode
        memcpy(buf + 1, s_oled_fb + page * 128, 128);
        esp_err_t err = i2c_master_write_to_device(
            I2C_PORT_OLED, OLED_ADDR, buf, 129, pdMS_TO_TICKS(50));
        if (err != ESP_OK) return err;
    }
    return ESP_OK;
}
 
static void oled_clear(void) { memset(s_oled_fb, 0, sizeof(s_oled_fb)); }
 
static void oled_draw_pixel(int x, int y, int on) {
    if (x < 0 || x >= 128 || y < 0 || y >= 64) return;
    int idx = x + (y / 8) * 128;
    if (on) s_oled_fb[idx] |=  (1 << (y % 8));
    else    s_oled_fb[idx] &= ~(1 << (y % 8));
}
 
static void oled_draw_char(int x, int y, char c, int on) {
    if (c < 32 || c > 127) c = ' ';
    int fi = c - 32;
    for (int row = 0; row < 8; row++) {
        uint8_t line = font8x8[fi][row];
        for (int col = 0; col < 8; col++)
            if (line & (1 << (7 - col)))
                oled_draw_pixel(x + col, y + row, on);
    }
}
 
static void oled_print(int col, int row, const char *str, int on) {
    // col, row เป็นหน่วย "ตัวอักษร" (8px) ตรงกับ block Print(col, row)
    int x = col * 8;
    int y = row * 8;
    while (*str) { oled_draw_char(x, y, *str++, on); x += 8; }
}
 
// ---- I2C init (auto-scan SDA/SCL) ----
static void i2c_master_init(void) {
    struct { int sda; int scl; } cands[] = {{21,22},{4,5},{8,9}};
    for (int i = 0; i < 3; i++) {
        i2c_config_t conf = {
            .mode = I2C_MODE_MASTER,
            .sda_io_num = cands[i].sda, .sda_pullup_en = GPIO_PULLUP_ENABLE,
            .scl_io_num = cands[i].scl, .scl_pullup_en = GPIO_PULLUP_ENABLE,
            .master.clk_speed = 400000,
        };
        i2c_driver_delete(I2C_PORT_OLED);
        if (i2c_param_config(I2C_PORT_OLED, &conf) != ESP_OK) continue;
        if (i2c_driver_install(I2C_PORT_OLED, I2C_MODE_MASTER, 0, 0, 0) != ESP_OK) continue;
        vTaskDelay(pdMS_TO_TICKS(30));
 
        // ลอง ping 0x3C
        i2c_cmd_handle_t cmd = i2c_cmd_link_create();
        i2c_master_start(cmd);
        i2c_master_write_byte(cmd, (OLED_ADDR << 1) | I2C_MASTER_WRITE, true);
        i2c_master_stop(cmd);
        esp_err_t err = i2c_master_cmd_begin(I2C_PORT_OLED, cmd, pdMS_TO_TICKS(50));
        i2c_cmd_link_delete(cmd);
        if (err == ESP_OK) {
            ESP_LOGI(TAG, "OLED found on SDA=%d SCL=%d", cands[i].sda, cands[i].scl);
            return;
        }
    }
    // fallback
    i2c_driver_delete(I2C_PORT_OLED);
    i2c_config_t conf = {
        .mode = I2C_MODE_MASTER, .sda_io_num = 21, .sda_pullup_en = GPIO_PULLUP_ENABLE,
        .scl_io_num = 22,        .scl_pullup_en = GPIO_PULLUP_ENABLE,
        .master.clk_speed = 100000,
    };
    i2c_param_config(I2C_PORT_OLED, &conf);
    i2c_driver_install(I2C_PORT_OLED, I2C_MODE_MASTER, 0, 0, 0);
}
 
// ================================================================
void app_main(void) {
    ESP_LOGI(TAG, "Booting...");
 
    i2c_master_init();
    if (sh1106_init() == ESP_OK) ESP_LOGI(TAG, "OLED OK");
    else                         ESP_LOGE(TAG, "OLED FAIL");
 
    // ---- ADC setup ----
    adc_oneshot_unit_handle_t adc1;
    adc_oneshot_unit_init_cfg_t adc_cfg = {
        .unit_id  = ADC_UNIT_1,
        .ulp_mode = ADC_ULP_MODE_DISABLE,
    };
    ESP_ERROR_CHECK(adc_oneshot_new_unit(&adc_cfg, &adc1));
 
    adc_oneshot_chan_cfg_t ch_cfg = {
        .bitwidth = ADC_BITWIDTH_DEFAULT,
        .atten    = ADC_ATTEN_DB_12,
    };
    ESP_ERROR_CHECK(adc_oneshot_config_channel(adc1, JS_X_CHAN, &ch_cfg));
    ESP_ERROR_CHECK(adc_oneshot_config_channel(adc1, JS_Y_CHAN, &ch_cfg));
 
    char val_str[16];
 
    // ---- แสดง header ครั้งเดียว ----
    oled_clear();
    oled_print(4, 2, "Remote Testing", 1);  // Print(4, 2, "Remote Testing")
    sh1106_update();
 
    // ---- Loop ----
    while (1) {
        int raw_x = 0, raw_y = 0;
        adc_oneshot_read(adc1, JS_X_CHAN, &raw_x);  // GPIO34 S2 ซ้าย-ขวา
        adc_oneshot_read(adc1, JS_Y_CHAN, &raw_y);  // GPIO35 S1 ขึ้น-ลง
 
        ESP_LOGI(TAG, "X(GPIO34)=%d  Y(GPIO35)=%d", raw_x, raw_y);
 
        // วาด header คงไว้, อัปเดตเฉพาะบรรทัด X, Y
        // ล้างเฉพาะโซนค่า (col 8 ถึงขอบจอ)
        // ง่ายกว่า: clear ทั้งหมด วาดใหม่
        oled_clear();
        oled_print(4, 2, "Remote Testing", 1); // row 2
 
        oled_print(4, 4, "X = ", 1);            // Print(4, 4, "X = ")
        snprintf(val_str, sizeof(val_str), "%d", raw_x);
        oled_print(8, 4, val_str, 1);           // Print(8, 4, mJoystick X)
 
        oled_print(4, 6, "Y = ", 1);            // Print(4, 6, "Y = ")
        snprintf(val_str, sizeof(val_str), "%d", raw_y);
        oled_print(8, 6, val_str, 1);           // Print(8, 6, mJoystick Y)
 
        sh1106_update();
 
        vTaskDelay(pdMS_TO_TICKS(200));          // Delay 0.2 s
    }
 
    adc_oneshot_del_unit(adc1);
}